"""Explicit-input ESP32 firmware scaffolding and GPIO/net consistency checks.

Generated output is a buildable-shape starter project, not application firmware,
a board-qualified pinout, or evidence that the connected circuit is electrically safe.
"""
from __future__ import annotations

import hashlib
import io
import json
import re
import zipfile
from typing import Any

_TARGET = "esp32dev"
_SIGNAL_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,31}$")
_AVAILABLE_GPIOS = frozenset({*range(0, 6), *range(12, 20), 21, 22, 23, 25, 26, 27, *range(32, 40)})
_INPUT_ONLY_GPIOS = frozenset(range(34, 40))
_STRAPPING_GPIOS = frozenset({0, 2, 5, 12, 15})
_UART_GPIOS = frozenset({1, 3})


def generate_esp32_scaffold(request: Any, circuit_model: Any) -> dict[str, Any]:
    """Validate explicit GPIO-to-net assignments and render a minimal Arduino scaffold."""
    if not isinstance(request, dict) or set(request) != {"target", "pins"}:
        raise ValueError("Firmware scaffold request must contain exactly target and pins")
    if request["target"] != _TARGET:
        raise ValueError(f"Unsupported firmware target {request['target']!r}; supported target is 'esp32dev'")
    if not isinstance(circuit_model, dict) or not isinstance(circuit_model.get("nets"), list):
        raise ValueError("A validated circuit model with named nets is required")
    net_names = {net["name"] for net in circuit_model["nets"]
                 if isinstance(net, dict) and isinstance(net.get("name"), str)}
    pins = request["pins"]
    if not isinstance(pins, list) or not 1 <= len(pins) <= 32:
        raise ValueError("pins must contain between 1 and 32 explicit signal mappings")

    normalized: list[dict[str, Any]] = []
    signals: set[str] = set()
    gpios: set[int] = set()
    warnings: list[str] = [
        "The generic ESP32 Dev Module target is explicit, but the exact board/module revision and peripheral wiring are not identified.",
        "GPIO-to-net bindings are user assertions; this scaffold does not verify voltage levels, loads, external circuitry, or electrical safety.",
        "Generated code only initializes assigned pin modes. Application behavior, timing, and device drivers are not implemented.",
    ]
    for index, item in enumerate(pins):
        if not isinstance(item, dict) or set(item) != {"signal", "gpio", "direction", "net"}:
            raise ValueError(f"pins[{index}] must contain exactly signal, gpio, direction, and net")
        signal, gpio, direction, net = item["signal"], item["gpio"], item["direction"], item["net"]
        if not isinstance(signal, str) or not _SIGNAL_RE.fullmatch(signal):
            raise ValueError(f"pins[{index}].signal must be a simple identifier (1–32 letters, digits, or underscores; starts with a letter)")
        signal_key = signal.casefold()
        if signal_key in signals:
            raise ValueError(f"duplicate firmware signal name: {signal}")
        signals.add(signal_key)
        if type(gpio) is not int or gpio not in _AVAILABLE_GPIOS:
            raise ValueError(f"{signal} GPIO must be one of the exposed ESP32 Dev Module pins")
        if gpio in gpios:
            raise ValueError(f"GPIO{gpio} is assigned more than once")
        gpios.add(gpio)
        if not isinstance(direction, str) or direction not in {"input", "output"}:
            raise ValueError(f"{signal} direction must be 'input' or 'output'")
        if direction == "output" and gpio in _INPUT_ONLY_GPIOS:
            raise ValueError(f"GPIO{gpio} is input-only and cannot be assigned to output signal {signal}")
        if not isinstance(net, str) or net not in net_names:
            raise ValueError(f"{signal} must reference an existing named circuit net")
        normalized.append({"signal": signal, "gpio": gpio, "direction": direction, "net": net})
        if gpio in _STRAPPING_GPIOS:
            warnings.append(f"GPIO{gpio} ({signal}) is a boot-strapping pin; external circuitry may affect boot mode.")
        if gpio in _UART_GPIOS:
            warnings.append(f"GPIO{gpio} ({signal}) is commonly used for UART0; serial logging/programming may conflict.")
        if gpio in _INPUT_ONLY_GPIOS:
            warnings.append(f"GPIO{gpio} ({signal}) is input-only and has no internal pull-up/down capability on the classic ESP32 target.")

    normalized.sort(key=lambda item: (item["gpio"], item["signal"].casefold()))
    declarations = []
    initializers = []
    for item in normalized:
        symbol = re.sub(r"[^A-Za-z0-9_]", "_", item["signal"]).upper()
        declarations.append(f"constexpr uint8_t GPIO_{symbol} = {item['gpio']};")
        mode = "OUTPUT" if item["direction"] == "output" else "INPUT"
        initializers.append(f"  pinMode(GPIO_{symbol}, {mode});")
    source = "\n".join([
        "// Generated by CIRCUITMIND AI: explicit pin-mode scaffold only.",
        "// Review the exact board pinout and connected circuit before building or powering hardware.",
        "#include <Arduino.h>",
        "",
        "namespace {",
        *[f"  {line}" for line in declarations],
        "}",
        "",
        "void setup() {",
        "  Serial.begin(115200);",
        *initializers,
        "}",
        "",
        "void loop() {",
        "  // TODO: add reviewed application behavior and timing requirements.",
        "  delay(10);",
        "}",
        "",
    ])
    platformio = "\n".join([
        "; Generic PlatformIO ESP32 Dev Module scaffold; board-specific build not verified.",
        "[env:esp32dev]",
        "platform = espressif32",
        "board = esp32dev",
        "framework = arduino",
        "monitor_speed = 115200",
        "",
    ])
    circuit_model_sha256 = hashlib.sha256(json.dumps(circuit_model, sort_keys=True, separators=(",", ":"),
                                            ensure_ascii=False, allow_nan=False).encode("utf-8")).hexdigest()
    configuration_sha256 = hashlib.sha256(json.dumps(request, sort_keys=True, separators=(",", ":"),
                                               ensure_ascii=False, allow_nan=False).encode("utf-8")).hexdigest()
    manifest = {
        "schema_version": 1,
        "target": _TARGET,
        "circuit_model_sha256": circuit_model_sha256,
        "configuration_sha256": configuration_sha256,
        "framework": "arduino",
        "pin_mappings": normalized,
        "compile_status": "not-run",
        "limitations": warnings,
        "scope": "Generated starter files initialize explicit GPIO pin modes only; they do not implement the requested application or validate hardware.",
    }
    manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")
    source_bytes = source.encode("utf-8")
    platformio_bytes = platformio.encode("utf-8")
    archive_buffer = io.BytesIO()
    with zipfile.ZipFile(archive_buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in (("firmware_manifest.json", manifest_bytes),
                              ("platformio.ini", platformio_bytes),
                              ("src/main.cpp", source_bytes)):
            entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, content)
    archive_bytes = archive_buffer.getvalue()
    return {
        "manifest": manifest,
        "files": {"platformio.ini": platformio_bytes, "src/main.cpp": source_bytes,
                  "firmware_project.zip": archive_bytes},
        "sha256": {"manifest": hashlib.sha256(manifest_bytes).hexdigest(),
                   "platformio.ini": hashlib.sha256(platformio_bytes).hexdigest(),
                   "src/main.cpp": hashlib.sha256(source_bytes).hexdigest(),
                   "firmware_project.zip": hashlib.sha256(archive_bytes).hexdigest()},
    }
